"""Write docs/THIRD_PARTY_LICENSES.md for the runtime dependency closure of the installed package.

Usage: python scripts/gen_third_party_licenses.py   (inside an environment where kaizeval is installed)
"""

from __future__ import annotations

import re
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

ROOT = "kaizeval"
EXTRAS = {"postgres", "s3"}  # optional runtime extras are listed too, when installed
COPYLEFT = re.compile(r"\b(AGPL|GPL|LGPL|SSPL|EUPL|CC-BY-NC)\b", re.IGNORECASE)


def license_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "UNKNOWN"


def closure() -> dict[str, metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    queue = [(ROOT, EXTRAS)]
    while queue:
        name, extras = queue.pop()
        key = re.sub(r"[-_.]+", "-", name).lower()
        if key in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        seen[key] = dist
        for raw in dist.requires or []:
            req = Requirement(raw)
            if req.marker is not None:
                environments = [{"extra": e} for e in extras] or [{"extra": ""}]
                if not any(req.marker.evaluate(env) for env in environments):
                    continue
            queue.append((req.name, set(req.extras)))
    seen.pop(ROOT, None)
    return seen


def main() -> None:
    rows, flagged = [], []
    for key, dist in sorted(closure().items()):
        lic = license_of(dist)
        rows.append(f"| {dist.metadata['Name']} | {dist.version} | {lic} |")
        if COPYLEFT.search(lic) and "LGPL" not in lic.upper():
            flagged.append(f"{dist.metadata['Name']} ({lic})")
    out = [
        "# Third-party licenses (Python runtime dependencies)", "",
        "Generated by `python scripts/gen_third_party_licenses.py` from the metadata of the installed",
        "packages. Kaizeval does not bundle these packages; they are installed by `pip` and remain under",
        "their own licenses. Versions reflect the environment the list was generated in.", "",
        f"Packages: {len(rows)}. Strong-copyleft licenses detected: {', '.join(flagged) if flagged else 'none'}.", "",
        "| Package | Version | License |", "|---|---|---|", *rows, "",
    ]
    path = Path(__file__).resolve().parents[1] / "docs" / "THIRD_PARTY_LICENSES.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(rows)} packages; flagged: {flagged or 'none'}")


if __name__ == "__main__":
    main()
